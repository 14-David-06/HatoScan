import type { ReactNode, SVGProps } from 'react';

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'children'> {
  /** Lado en píxeles. Por defecto 1em: el icono sigue el tamaño del texto que acompaña. */
  readonly size?: number | string;
  /** Texto para lectores de pantalla. Sin él, el icono es decorativo. */
  readonly title?: string;
}

/**
 * Base de todos los iconos: rejilla de 24, trazo de 1.75 y color heredado. Una pantalla que
 * necesite un icono nuevo lo define con este componente para mantener el mismo trazo.
 */
export function Icon({
  size = '1em',
  title,
  className,
  children,
  ...rest
}: IconProps & { readonly children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className ? `icon ${className}` : 'icon'}
      role={title ? 'img' : undefined}
      aria-hidden={title ? undefined : true}
      focusable="false"
      {...rest}
    >
      {title && <title>{title}</title>}
      {children}
    </svg>
  );
}

